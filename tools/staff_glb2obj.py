"""GLB (Sketchfab "Inspired by Stargate SG-1: Goa'Uld Staff Weapon" by Ska-Ara, CC-BY-NC-SA-4.0)
-> NeoForge OBJ item model for the staff weapon.

The staff lies along the mesh's local Z with the pointed emitter head at +Z (the rounded pommel at -Z).
It is turned upright (head up, +Y),
scaled to LENGTH blocks and centred on (0.5, 0.5, 0.5) so the item display transforms rotate it about its
middle. UVs are written as in glTF (V down), like tools/glb2obj.py: the NeoForge OBJ loader keeps them as-is.
The base colour texture is extracted next to the OBJ as staff_weapon_base.<ext>; downscale it with
    java tools/ToPng.java <extracted> src/main/resources/assets/stargate/textures/item/staff_weapon.png 1024

FR : le bâton est couché selon l'axe Z local, tête pointue (émetteur) vers +Z, pommeau arrondi vers -Z.
Il est redressé (tête vers +Y), mis à
LENGTH blocs et centré sur (0.5, 0.5, 0.5) pour que les transformations d'affichage le tournent autour de son
milieu. La texture de couleur est extraite à côté de l'OBJ ; la réduire avec ToPng (voir ci-dessus).

    python tools/staff_glb2obj.py <staff.glb> src/main/resources/assets/stargate/models/item/staff_weapon
"""
import json, os, struct, sys
import numpy as np

src, outdir = sys.argv[1], sys.argv[2]
LENGTH = 2.0  # blocks / blocs

d = open(src, 'rb').read()
clen = struct.unpack('<I', d[12:16])[0]
j = json.loads(d[20:20 + clen])
B = d[20 + clen + 8:]


def acc(i):
    a = j['accessors'][i]; bv = j['bufferViews'][a['bufferView']]
    n = {'SCALAR': 1, 'VEC2': 2, 'VEC3': 3, 'VEC4': 4}[a['type']]
    dt = {5126: np.float32, 5125: np.uint32, 5123: np.uint16, 5121: np.uint8}[a['componentType']]
    off = bv.get('byteOffset', 0) + a.get('byteOffset', 0); sz = n * np.dtype(dt).itemsize
    stride = bv.get('byteStride') or sz
    raw = np.frombuffer(B, np.uint8, (a['count'] - 1) * stride + sz, off)
    rows = np.lib.stride_tricks.as_strided(raw, shape=(a['count'], sz), strides=(stride, 1)).copy()
    return rows.view(dt).reshape(a['count'], n)


prim = j['meshes'][0]['primitives'][0]
at = prim['attributes']
pos = acc(at['POSITION']).astype(float)
nor = acc(at['NORMAL']).astype(float)
uv = acc(at['TEXCOORD_0']).astype(float)
tris = acc(prim['indices']).reshape(-1, 3).astype(int)

# local (x, y, z) -> (x, z, -y): upright, head (+z) up; a proper rotation (det = +1)
# local (x, y, z) -> (x, z, -y) : debout, tête (+z) en haut ; rotation propre (dét = +1)
R = np.array([[1, 0, 0], [0, 0, 1], [0, -1, 0]], float)
p = pos @ R.T; n = nor @ R.T
lo, hi = p.min(0), p.max(0)
S = LENGTH / (hi[1] - lo[1])
p = (p - (lo + hi) / 2) * S + 0.5
print('bounds (blocks):', p.min(0).round(3), p.max(0).round(3), 'triangles:', len(tris))

os.makedirs(outdir, exist_ok=True)
with open(os.path.join(outdir, 'staff_weapon.mtl'), 'w', newline='\n') as f:
    f.write('# Goa\'uld staff weapon, from "Inspired by Stargate SG-1: Goa\'Uld Staff Weapon" by Ska-Ara '
            '(CC-BY-NC-SA-4.0)\n\nnewmtl staff\nKd 1 1 1\nKa 0 0 0\nmap_Kd #staff\n')
with open(os.path.join(outdir, 'staff_weapon.obj'), 'w', newline='\n') as f:
    f.write('# Generated by tools/staff_glb2obj.py from "Inspired by Stargate SG-1: Goa\'Uld Staff Weapon"\n'
            '# by Ska-Ara (https://sketchfab.com/ska-ara), CC-BY-NC-SA-4.0\n'
            'mtllib staff_weapon.mtl\no staff\nusemtl staff\n')
    f.write(''.join(f'v {v[0]:.5f} {v[1]:.5f} {v[2]:.5f}\n' for v in p))
    f.write(''.join(f'vt {t[0]:.5f} {t[1]:.5f}\n' for t in uv))
    f.write(''.join(f'vn {v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n' for v in n))
    f.write(''.join('f ' + ' '.join(f'{i + 1}/{i + 1}/{i + 1}' for i in t) + '\n' for t in tris))


img = j['images'][j['textures'][j['materials'][0]['pbrMetallicRoughness']['baseColorTexture']['index']]['source']]
bv = j['bufferViews'][img['bufferView']]
ext = 'jpg' if 'jpeg' in img['mimeType'] else 'png'
out = os.path.join(outdir, 'staff_weapon_base.' + ext)
open(out, 'wb').write(B[bv.get('byteOffset', 0):bv.get('byteOffset', 0) + bv['byteLength']])
print('texture:', out)
