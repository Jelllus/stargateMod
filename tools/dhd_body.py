"""Generates the static body of the DHD (pedestal + tilted console disc + rim) as a NeoForge OBJ.
The keys and the dome are drawn by DhdRenderer so they can light up; their layout lives in DhdLayout.java.
Keep the console constants below in sync with DhdLayout.

Génère le corps fixe du DHD (pied + disque de console incliné + rebord) en OBJ NeoForge.
Les touches et le dôme sont dessinés par DhdRenderer pour pouvoir s'allumer ; leur disposition est dans
DhdLayout.java. Garder les constantes de console ci-dessous synchronisées avec DhdLayout.

    python tools/dhd_body.py src/main/resources/assets/stargate/models/block/dhd
"""
import math, os, sys

out_dir = sys.argv[1]
TILT = math.radians(25.0)
CX, CY, CZ = 0.5, 0.86, 0.5          # console surface centre (DhdLayout.CX/CY/CZ)
CONSOLE_R = 0.47                      # DhdLayout.CONSOLE_RADIUS
CONSOLE_THICK = 0.06
LIP_R0, LIP_H = 0.458, 0.026          # raised rim outside the outer key ring
SEG = 48

N = (0.0, math.cos(TILT), math.sin(TILT))
E1 = (1.0, 0.0, 0.0)
E2 = (0.0, math.sin(TILT), -math.cos(TILT))

verts, norms, faces = [], [], []   # faces: (material, [(vi, ni), ...])

def v(p):
    verts.append(p); return len(verts)
def n(d):
    l = math.sqrt(sum(c * c for c in d)) or 1.0
    norms.append(tuple(c / l for c in d)); return len(norms)
def quad(mat, a, b, c, d, normal):
    k = n(normal); faces.append((mat, [(a, k), (b, k), (c, k), (d, k)]))

def console_point(r, ang, h):
    a, b = r * math.cos(ang), r * math.sin(ang)
    return (CX + a * E1[0] + b * E2[0] + h * N[0], CY + a * E1[1] + b * E2[1] + h * N[1], CZ + a * E1[2] + b * E2[2] + h * N[2])

def ring_band(mat, r0, r1, h0, h1, top=True, outer_side=True, inner_side=False, bottom=False):
    """Annulus between radii r0..r1 on the console, from height h0 to h1 (along the normal)."""
    for i in range(SEG):
        a0, a1 = 2 * math.pi * i / SEG, 2 * math.pi * (i + 1) / SEG
        P = lambda r, a, h: v(console_point(r, a, h))
        am = (a0 + a1) / 2
        radial = (math.cos(am) * E1[0] + math.sin(am) * E2[0], math.cos(am) * E1[1] + math.sin(am) * E2[1], math.cos(am) * E1[2] + math.sin(am) * E2[2])
        if top and r1 > r0:
            quad(mat, P(r0, a0, h1), P(r1, a0, h1), P(r1, a1, h1), P(r0, a1, h1), N)
        if bottom and r1 > r0:
            quad(mat, P(r0, a1, h0), P(r1, a1, h0), P(r1, a0, h0), P(r0, a0, h0), tuple(-c for c in N))
        if outer_side:
            quad(mat, P(r1, a0, h1), P(r1, a0, h0), P(r1, a1, h0), P(r1, a1, h1), radial)
        if inner_side:
            quad(mat, P(r0, a1, h1), P(r0, a1, h0), P(r0, a0, h0), P(r0, a0, h1), tuple(-c for c in radial))

# Console: top surface (under the keys), outer edge, bottom. / Console : dessus (sous les touches), tranche, dessous.
ring_band('dhd_console', 0.0, CONSOLE_R, -CONSOLE_THICK, 0.0, top=True, outer_side=True, bottom=True)
ring_band('dhd_rim', LIP_R0, CONSOLE_R, 0.0, LIP_H, top=True, outer_side=True, inner_side=True)

# Pedestal: octagonal frustum with a flared base. / Pied : tronc octogonal à base évasée.
def frustum(mat, y0, y1, r0, r1, sides=8, cap_top=False, cap_bottom=False):
    off = math.pi / sides
    for i in range(sides):
        a0, a1 = off + 2 * math.pi * i / sides, off + 2 * math.pi * (i + 1) / sides
        p = lambda r, a, y: v((0.5 + r * math.cos(a), y, 0.5 + r * math.sin(a)))
        am = (a0 + a1) / 2
        slope = (r0 - r1) / max(y1 - y0, 1e-6)
        quad(mat, p(r0, a1, y0), p(r0, a0, y0), p(r1, a0, y1), p(r1, a1, y1), (math.cos(am), slope, math.sin(am)))
        if cap_top:
            k = n((0, 1, 0)); faces.append((mat, [(p(r1, a1, y1), k), (p(r1, a0, y1), k), (v((0.5, y1, 0.5)), k)]))
        if cap_bottom:
            k = n((0, -1, 0)); faces.append((mat, [(p(r0, a0, y0), k), (p(r0, a1, y0), k), (v((0.5, y0, 0.5)), k)]))

frustum('dhd_stone', 0.00, 0.06, 0.36, 0.34, cap_bottom=True, cap_top=True)   # base plate / socle
frustum('dhd_stone', 0.06, 0.14, 0.30, 0.22, cap_top=True)                    # flare / évasement
frustum('dhd_pillar', 0.14, 0.80, 0.20, 0.15)                                 # column / colonne
frustum('dhd_stone', 0.62, 0.70, 0.17, 0.21, cap_top=True)                    # collar under the console / collier

os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, 'dhd.obj'), 'w', newline='\n') as f:
    f.write('# Original DHD body, generated by tools/dhd_body.py\nmtllib dhd.mtl\nvt 0.5 0.5\n')
    for p in verts: f.write(f'v {p[0]:.5f} {p[1]:.5f} {p[2]:.5f}\n')
    for d in norms: f.write(f'vn {d[0]:.4f} {d[1]:.4f} {d[2]:.4f}\n')
    cur = None
    for mat, fv in faces:
        if mat != cur:
            f.write(f'usemtl {mat}\n'); cur = mat
        f.write('f ' + ' '.join(f'{a}/1/{b}' for a, b in fv) + '\n')
with open(os.path.join(out_dir, 'dhd.mtl'), 'w', newline='\n') as f:
    f.write('# Original DHD body materials (flat colours over a white texture)\n')
    for name, kd in (('dhd_stone', '0.50 0.47 0.43'), ('dhd_pillar', '0.42 0.40 0.37'),
                     ('dhd_console', '0.36 0.35 0.36'), ('dhd_rim', '0.62 0.60 0.56')):
        f.write(f'\nnewmtl {name}\nKd {kd}\nKa 0 0 0\nmap_Kd #white\n')
print('faces', len(faces), 'verts', len(verts))
