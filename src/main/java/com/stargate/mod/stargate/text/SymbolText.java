package com.stargate.mod.stargate.text;

import com.stargate.mod.StargateMod;
import com.stargate.mod.stargate.address.StargateAddress;
import com.stargate.mod.stargate.address.StargateSymbol;
import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.FontDescription;
import net.minecraft.network.chat.MutableComponent;
import net.minecraft.network.chat.Style;
import net.minecraft.resources.Identifier;

/**
 * Text components that show addresses as their glyphs, using the {@code stargate:glyphs} bitmap font: symbol
 * {@code n} is the character U+E000 + n. The glyphs are the same as on the DHD keys (both generated by
 * {@code tools/DhdGlyphs.java}).
 *
 * <p><i>FR —</i> Composants de texte qui affichent les adresses sous forme de glyphes, avec la police bitmap
 * {@code stargate:glyphs} : le symbole {@code n} est le caractère U+E000 + n. Les glyphes sont les mêmes que
 * sur les touches du DHD (tous deux générés par {@code tools/DhdGlyphs.java}).
 */
public final class SymbolText {
    /**
     * The glyph font. / <i>FR —</i> La police des glyphes.
     */
    public static final FontDescription FONT =
            new FontDescription.Resource(Identifier.fromNamespaceAndPath(StargateMod.MODID, "glyphs"));

    private static final Style GLYPH_STYLE = Style.EMPTY.withFont(FONT).withColor(0xFFC27A);
    private static final int BASE = 0xE000;

    private SymbolText() {
    }

    /**
     * The character drawing a symbol in {@link #FONT}.
     *
     * <p><i>FR —</i> Le caractère qui dessine un symbole dans {@link #FONT}.
     *
     * @param symbol a symbol 1–38 / un symbole de 1 à 38
     * @return the character / le caractère
     */
    public static char glyph(StargateSymbol symbol) {
        return (char) (BASE + symbol.id());
    }

    /**
     * An address as glyphs only, e.g. for a compact display.
     *
     * <p><i>FR —</i> Une adresse sous forme de glyphes seuls, par exemple pour un affichage compact.
     *
     * @param address the address / l'adresse
     * @return a component in the glyph font / un composant dans la police des glyphes
     */
    public static MutableComponent glyphs(StargateAddress address) {
        StringBuilder sb = new StringBuilder(address.length() * 2);
        for (StargateSymbol s : address.symbols()) {
            if (!sb.isEmpty()) {
                sb.append(' ');
            }
            sb.append(glyph(s));
        }
        return Component.literal(sb.toString()).withStyle(GLYPH_STYLE);
    }

    /**
     * An address as glyphs followed by its numbers in grey, e.g. {@code ✶ ✷ ✸ ✹ ✺ ✻ (27-7-15-32-12-30)}.
     *
     * <p><i>FR —</i> Une adresse sous forme de glyphes suivis de ses numéros en gris, par exemple
     * {@code ✶ ✷ ✸ ✹ ✺ ✻ (27-7-15-32-12-30)}.
     *
     * @param address the address / l'adresse
     * @return the component / le composant
     */
    public static MutableComponent address(StargateAddress address) {
        return glyphs(address)
                .append(Component.literal(" (" + address + ")").withStyle(Style.EMPTY.withFont(FontDescription.DEFAULT).withColor(ChatFormatting.GRAY)));
    }
}
